-- Online Book Store setup script
-- Based on the project CSV files. Customer name, email, and phone values are synthetic placeholders.
-- Run on a fresh MySQL database to create the tables and load the sample data.

CREATE DATABASE IF NOT EXISTS onlinebookstore;
USE onlinebookstore;

CREATE TABLE IF NOT EXISTS books (
  Book_ID INT NOT NULL,
  Title VARCHAR(150) NOT NULL,
  Author VARCHAR(100) NOT NULL,
  Genre VARCHAR(80) NOT NULL,
  Published_Year SMALLINT NOT NULL,
  Price DECIMAL(10,2) NOT NULL,
  Stock INT NOT NULL,
  PRIMARY KEY (Book_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS customers (
  Customer_ID INT NOT NULL,
  Name VARCHAR(100) NOT NULL,
  Email VARCHAR(255) NOT NULL,
  Phone VARCHAR(30) NOT NULL,
  City VARCHAR(100) NOT NULL,
  Country VARCHAR(100) NOT NULL,
  PRIMARY KEY (Customer_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS orders (
  Order_ID INT NOT NULL,
  Customer_ID INT NOT NULL,
  Book_ID INT NOT NULL,
  Order_Date DATE NOT NULL,
  Quantity INT NOT NULL,
  Total_Amount DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (Order_ID),
  CONSTRAINT fk_orders_customers FOREIGN KEY (Customer_ID) REFERENCES customers (Customer_ID),
  CONSTRAINT fk_orders_books FOREIGN KEY (Book_ID) REFERENCES books (Book_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

